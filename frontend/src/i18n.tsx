const messages: Record<Lang, Record<Key, string>> = { ru, en };

export function detectLang(): Lang {
  const stored = typeof localStorage === 'undefined' ? null : localStorage.getItem(STORAGE_KEY);
  if (stored === 'ru' || stored === 'en') return stored;
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function format(template: string, params?: Record<string, string | number>): string {
  return params ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`)) : template;
}

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  return format(messages[lang][key] ?? messages.ru[key], params);
}

/** Skill and theme codes come from the API; unknown codes fall back to the raw code. */
export function nameOf(lang: Lang, prefix: 'skill' | 'theme' | 'topic', code: string): string {
  const key = `${prefix}.${code}` as Key;
  return messages[lang][key] ?? code;
}

const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: 'ru', setLang: () => {} });

export function LangProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(initial ?? detectLang());
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = (next: Lang) => { localStorage.setItem(STORAGE_KEY, next); setLangState(next); };
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useT() {
  const { lang, setLang } = useContext(LangContext);
  return { lang, setLang, t: (key: Key, params?: Record<string, string | number>) => translate(lang, key, params), name: (prefix: 'skill' | 'theme' | 'topic', code: string) => nameOf(lang, prefix, code) };
}

export function LangToggle() {
  const { lang, setLang, t } = useT();
  return <button type="button" className="link lang" lang={lang === 'ru' ? 'en' : 'ru'} aria-label={t('lang.switchAria')} onClick={() => setLang(lang === 'ru' ? 'en' : 'ru')}>{t('lang.switch')}</button>;
}
